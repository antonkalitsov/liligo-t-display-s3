/*
  T-Display-S3 BLE Ticker
  ------------------------------------------------------------
  - Shows text presets (text, font, size, colors, animation, speed, brightness)
  - Presets are uploaded over Bluetooth LE from the web app and stored in flash
  - Runs standalone afterwards

  Buttons
    KEY  (GPIO14)  short  = next preset
                   long   = power off (deep sleep). Press KEY again to wake.
    BOOT (GPIO0)   short  = Bluetooth on/off (on for 2 min, or while connected)
                   long   = info screen (battery, Bluetooth name)

  BLE protocol: newline-terminated JSON on the RX characteristic,
  replies as newline-terminated JSON notifications on TX (sent in chunks).
*/
